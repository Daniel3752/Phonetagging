// Generates migrations/0011_app_rules_seed.sql — the per-rung app matrix decided with the operator.
//
// RECORDS INTENT ONLY. App control is enforced by Headwind, which is not on the phone yet, and the
// per-rung policies (apps_rung_1..5) carry no headwind_configuration_id until re-enrolment. Exact
// package names should be reconciled against the device's installed-apps list in Headwind then — the
// ones below are best-known, and 24Six's is a PLACEHOLDER to confirm.
//
// This is the SPECIFIC apps discussed, not a complete launcher allowlist. The full set of permitted
// apps per rung is still to be decided; here we lock the ones we talked through.
//
// Run:  node scripts/build-app-rules-seed.mjs

import { writeFileSync } from 'node:fs';

// package -> per-rung state. 'allowed' shows on that rung's launcher; 'blocked' is denied there.
// X (twitter) is blocked on EVERY rung as an app (site x.com is allowed at rung 5 via the web
// filter, not here). AI apps are allowed only at rung 5; on 2-4 the plan is web-only (a web-filter
// decision, so no app row makes them available). 24Six is the kosher-music app, allowed everywhere.
const APPS = {
  'com.whatsapp':                    { label: 'WhatsApp', states: { 1: 'blocked', 2: 'allowed', 3: 'allowed', 4: 'allowed', 5: 'allowed' } },
  'com.twentyfoursix.app':           { label: '24Six (CONFIRM package)', states: { 1: 'allowed', 2: 'allowed', 3: 'allowed', 4: 'allowed', 5: 'allowed' } },
  'com.spotify.music':               { label: 'Spotify', states: { 1: 'blocked', 2: 'blocked', 3: 'blocked', 4: 'allowed', 5: 'allowed' } },
  'com.twitter.android':             { label: 'X', states: { 1: 'blocked', 2: 'blocked', 3: 'blocked', 4: 'blocked', 5: 'blocked' } },
  'com.openai.chatgpt':              { label: 'ChatGPT', states: { 1: 'blocked', 2: 'blocked', 3: 'blocked', 4: 'blocked', 5: 'allowed' } },
  'com.anthropic.claude':            { label: 'Claude', states: { 1: 'blocked', 2: 'blocked', 3: 'blocked', 4: 'blocked', 5: 'allowed' } },
  'com.google.android.apps.bard':    { label: 'Gemini', states: { 1: 'blocked', 2: 'blocked', 3: 'blocked', 4: 'blocked', 5: 'allowed' } },
};

const rows = [];
for (const [pkg, { states }] of Object.entries(APPS)) {
  for (const rung of [1, 2, 3, 4, 5]) {
    rows.push({ policy: `apps_rung_${rung}`, pkg, state: states[rung] });
  }
}

const values = rows.map((r) => `  ('${r.policy}', '${r.pkg}', '${r.state}')`).join(',\n');

const sql = `-- Per-rung app matrix (intent only; enforced by Headwind after re-enrolment). GENERATED by
-- scripts/build-app-rules-seed.mjs. ${rows.length} rows across the five app policies. Package names are
-- best-known; reconcile against Headwind's installed-apps list on the phone. 24Six's package is a
-- PLACEHOLDER to confirm. X app is blocked on every rung (x.com allowed at rung 5 by the web filter);
-- AI apps allowed only at rung 5 (web-only on 2-4). Re-runnable (clears the seeded policies first).

DELETE FROM app_rules WHERE policy_id IN ('apps_rung_1','apps_rung_2','apps_rung_3','apps_rung_4','apps_rung_5');

INSERT INTO app_rules (policy_id, package_name, state)
VALUES
${values};
`;

writeFileSync(new URL('../migrations/0011_app_rules_seed.sql', import.meta.url), sql);
console.log(`Wrote migrations/0011_app_rules_seed.sql with ${rows.length} rows.`);
