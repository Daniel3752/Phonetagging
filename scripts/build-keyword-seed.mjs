// Generates migrations/0010_keyword_seed.sql — the starter keyword pre-filter for search queries.
//
// A rule carries a RATING on the same 2..6 ladder as everything else, and the pre-filter takes the
// STRICTEST matching rule (keywords.js). That property is what makes the allow-list safe: a benign
// word rated 2 (instant allow, no model call) is overridden the moment a block word also matches, so
// "kosher recipe" allows but "sexy recipe" blocks. Matching is WHOLE-WORD (see queryTokens), so
// "sex" does not fire on "essex".
//
// Deliberately CONSERVATIVE and short. Keywords only shed load from the model on the obvious cases;
// the model is the backstop for everything else and handles all languages (per its prompt), so the
// Hebrew/Yiddish block lists are intentionally minimal and meant for a native reviewer to extend.
//
// Run:  node scripts/build-keyword-seed.mjs

import { writeFileSync } from 'node:fs';

// rating 6 — NEVER (blocked at every rung). Unambiguous explicit terms that essentially never occur
// in a legitimate query. Ambiguous single words ("sex") are deliberately LEFT OUT so the model can
// judge "sex education" vs the obvious; put only multi-word explicit phrases for those.
const BLOCK_NEVER = [
  ['en', 'porn'], ['en', 'porno'], ['en', 'pornography'], ['en', 'xxx'], ['en', 'nude'],
  ['en', 'nudes'], ['en', 'naked'], ['en', 'nsfw'], ['en', 'hentai'], ['en', 'playboy'],
  ['en', 'onlyfans'], ['en', 'camgirl'], ['en', 'escort'], ['en', 'hookup'], ['en', 'sexy'],
  ['en', 'sex video'], ['en', 'sex tape'], ['en', 'adult video'],
];

// rating 5 — immodest / shtus (blocked at rungs 2-4, allowed at rung 5). Clearly-immodest clothing
// and appearance terms; borderline ones (swimsuit, bra) are left to the model.
const BLOCK_IMMODEST = [
  ['en', 'bikini'], ['en', 'lingerie'], ['en', 'cleavage'], ['en', 'miniskirt'],
  ['en', 'swimwear'], ['en', 'model photoshoot'], ['en', 'immodest'],
];

// rating 2 — essential / clean-general (instant allow, no model call). Safe because a block word in
// the same query wins. Torah terms in English transliteration and Hebrew.
const ALLOW_CLEAN = [
  ['en', 'torah'], ['en', 'halacha'], ['en', 'gemara'], ['en', 'mishnah'], ['en', 'chumash'],
  ['en', 'daf yomi'], ['en', 'parsha'], ['en', 'zmanim'], ['en', 'davening'], ['en', 'kashrus'],
  ['en', 'siddur'], ['en', 'tehillim'], ['en', 'shabbos'], ['en', 'yeshiva'],
  ['en', 'weather'], ['en', 'recipe'], ['en', 'directions'], ['en', 'dictionary'],
  ['he', 'תורה'], ['he', 'הלכה'], ['he', 'גמרא'], ['he', 'משנה'], ['he', 'פרשה'], ['he', 'זמנים'],
];

const rows = [
  ...BLOCK_NEVER.map(([lang, p]) => ({ lang, pattern: p, rating: 6, note: 'explicit' })),
  ...BLOCK_IMMODEST.map(([lang, p]) => ({ lang, pattern: p, rating: 5, note: 'immodest' })),
  ...ALLOW_CLEAN.map(([lang, p]) => ({ lang, pattern: p, rating: 2, note: 'clean' })),
];

const esc = (s) => String(s).replace(/'/g, "''");
const values = rows.map((r) =>
  `  ('search', '${r.lang}', '${esc(r.pattern)}', ${r.rating}, '${r.note}')`).join(',\n');

const sql = `-- Starter keyword pre-filter for search queries. GENERATED by scripts/build-keyword-seed.mjs.
-- ${rows.length} rules on the 2..6 ladder (6 explicit, 5 immodest/shtus, 2 clean instant-allow). The
-- pre-filter takes the STRICTEST match, so allow-terms are overridden by any block-term in the same
-- query. Conservative on purpose: the model is the backstop and judges every language, so extend the
-- Hebrew/Yiddish block lists with a native reviewer. Re-runnable-ish: clears prior seeded rows first.

DELETE FROM keyword_rules WHERE note IN ('explicit', 'immodest', 'clean');

INSERT INTO keyword_rules (scope, lang, pattern, rating, note)
VALUES
${values};
`;

writeFileSync(new URL('../migrations/0010_keyword_seed.sql', import.meta.url), sql);
console.log(`Wrote migrations/0010_keyword_seed.sql with ${rows.length} rules.`);
