// Generates migrations/0009_classify_queue_seed.sql — a starter worklist of common domains for the
// background pre-classifier (src/preclassify.js) to judge ahead of anyone visiting, so the inline
// classifier stays a rare fallback.
//
// These are just DOMAINS to judge, not verdicts — the AI rates each on the 2-6 ladder when the cron
// reaches it. A domain already in url_verdicts (the seed, an operator override, an earlier inline
// hit) is retired without a model call, so overlap with the allowlist seed is harmless. Grouped by
// registrable domain; subdomains inherit.
//
// Run:  node scripts/build-classify-queue-seed.mjs

import { writeFileSync } from 'node:fs';

// A broad, deliberately mainstream set — the sites a general user actually lands on. The point is
// coverage of the common web so first-visits are cache hits; the AI decides each one's rung. Kept to
// registrable domains, lowercased, de-duped below.
const DOMAINS = [
  // Reference / education / knowledge
  'wikipedia.org', 'wiktionary.org', 'britannica.com', 'khanacademy.org', 'coursera.org', 'edx.org',
  'quizlet.com', 'sparknotes.com', 'wolframalpha.com', 'dictionary.com', 'thesaurus.com',
  'merriam-webster.com', 'grammarly.com', 'archive.org', 'gutenberg.org', 'stackexchange.com',
  // Tech / dev / software
  'github.com', 'gitlab.com', 'stackoverflow.com', 'developer.mozilla.org', 'w3schools.com',
  'npmjs.com', 'python.org', 'nodejs.org', 'microsoft.com', 'apple.com', 'adobe.com', 'zoom.us',
  'dropbox.com', 'notion.so', 'canva.com', 'cloudflare.com',
  // News / weather / info
  'apnews.com', 'reuters.com', 'bbc.com', 'npr.org', 'weather.com', 'accuweather.com', 'weather.gov',
  'timesofisrael.com', 'jpost.com', 'arutzsheva.com', 'vosizneias.com', 'matzav.com', 'yeshivaworld.com',
  'hamodia.com', 'collive.com',
  // Government / civic / finance
  'usa.gov', 'irs.gov', 'ssa.gov', 'usps.com', 'medlineplus.gov',
  'nih.gov', 'cdc.gov', 'mayoclinic.org', 'webmd.com', 'chase.com', 'bankofamerica.com', 'wellsfargo.com',
  'paypal.com', 'intuit.com',
  // Torah / Jewish
  'sefaria.org', 'chabad.org', 'aish.com', 'ou.org', 'torah.org', 'hebcal.com', 'artscroll.com',
  'kosher.com', 'star-k.org', 'ok.org', 'crcweb.org', 'yutorah.org', 'alldaf.org', 'dirshu.co.il',
  // Shopping / commerce (general)
  'amazon.com', 'ebay.com', 'walmart.com', 'target.com', 'costco.com', 'homedepot.com', 'lowes.com',
  'bestbuy.com', 'etsy.com', 'ikea.com', 'staples.com', 'bhphotovideo.com', 'newegg.com',
  // Travel / maps / local
  'openstreetmap.org', 'tripadvisor.com', 'booking.com', 'expedia.com', 'kayak.com', 'airbnb.com',
  'united.com', 'delta.com', 'aa.com',
  // Productivity / mail / general
  'google.com', 'gmail.com', 'outlook.com', 'yahoo.com', 'wikimedia.org', 'mozilla.org',
  // Media / entertainment (rated by the AI — likely 4, or 5 if shtus)
  'youtube.com', 'spotify.com', 'imdb.com', 'espn.com', 'nba.com', 'goodreads.com',
];

const seen = new Set();
const domains = [];
for (const d of DOMAINS) {
  const host = String(d).trim().toLowerCase();
  if (host && host.includes('.') && !seen.has(host)) { seen.add(host); domains.push(host); }
}
domains.sort();

const now = Date.now();
const values = domains.map((d) => `  ('${d.replace(/'/g, "''")}', 'pending', 0, ${now})`).join(',\n');

const sql = `-- Starter worklist for the background pre-classifier. GENERATED by
-- scripts/build-classify-queue-seed.mjs. ${domains.length} common domains. Each is judged by the AI
-- on the cron tick; a domain already in url_verdicts is retired without a model call, so overlap with
-- the allowlist seed is harmless. Re-runnable (INSERT OR IGNORE on the domain primary key).

INSERT OR IGNORE INTO classify_queue (domain, status, attempts, added_at)
VALUES
${values};
`;

writeFileSync(new URL('../migrations/0009_classify_queue_seed.sql', import.meta.url), sql);
console.log(`Wrote migrations/0009_classify_queue_seed.sql with ${domains.length} domains.`);
